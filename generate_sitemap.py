
"""
Kailash Kalamkari - Google XML Sitemap Generator.

Source:
    products.csv (generated by generate_merchant_feed.py)

Rules:
    - Only active, in-stock products are included.
    - Invalid URLs or prices stop generation.
    - Existing sitemap is preserved on validation failure.
"""

import csv
import xml.etree.ElementTree as ET

from pathlib import Path
from urllib.parse import parse_qs, urlsplit


ROOT = Path(__file__).resolve().parent

FEED_FILE = ROOT / "products.csv"
OUTPUT_FILE = ROOT / "sitemap.xml"

SITE_URL = "https://www.kailash-kalamkari.com/"

SITEMAP_NS = (
    "http://www.sitemaps.org/schemas/sitemap/0.9"
)

IMAGE_NS = (
    "http://www.google.com/schemas/sitemap-image/1.1"
)

ET.register_namespace("", SITEMAP_NS)
ET.register_namespace("image", IMAGE_NS)

# Guard against accidentally publishing an incomplete feed.
MIN_PRODUCT_URLS = 1000


def add_url(root, link, image_link=""):
    entry = ET.SubElement(
        root,
        f"{{{SITEMAP_NS}}}url",
    )

    ET.SubElement(
        entry,
        f"{{{SITEMAP_NS}}}loc",
    ).text = link

    if image_link:
        image = ET.SubElement(
            entry,
            f"{{{IMAGE_NS}}}image",
        )

        ET.SubElement(
            image,
            f"{{{IMAGE_NS}}}loc",
        ).text = image_link


def validate_product_link(link, line_number):
    parsed = urlsplit(link)
    query = parse_qs(parsed.query)

    if (
        parsed.scheme != "https"
        or parsed.netloc != "www.kailash-kalamkari.com"
        or parsed.path not in ("", "/")
        or parsed.fragment
        or not query.get("product")
        or query.get("department", [""])[0]
        not in ("saree", "dupatta")
    ):
        raise ValueError(
            f"Invalid product URL on CSV row {line_number}: "
            f"{link}"
        )


def validate_image_link(link, line_number):
    if not link:
        raise ValueError(
            f"Missing product image on CSV row {line_number}"
        )

    parsed = urlsplit(link)

    if (
        parsed.scheme != "https"
        or not parsed.netloc
    ):
        raise ValueError(
            f"Invalid image URL on CSV row {line_number}"
        )


def validate_price(value, line_number):
    price_text = str(value or "").strip()

    if not price_text.endswith(" INR"):
        raise ValueError(
            f"Invalid feed price format on row {line_number}"
        )

    try:
        amount = float(
            price_text.removesuffix(" INR").strip()
        )
    except ValueError:
        raise ValueError(
            f"Invalid product price on row {line_number}"
        )

    if not (amount > 0):
        raise ValueError(
            f"Zero/negative price on row {line_number}"
        )


def main():
    if not FEED_FILE.is_file():
        raise FileNotFoundError(
            "products.csv missing. "
            "Run generate_merchant_feed.py first."
        )

    with FEED_FILE.open(
        "r",
        newline="",
        encoding="utf-8-sig",
    ) as source:
        reader = csv.DictReader(source)

        required = {
            "id",
            "link",
            "image_link",
            "availability",
            "price",
        }

        if not required.issubset(
            reader.fieldnames or []
        ):
            raise ValueError(
                "Merchant feed is missing required columns. "
                "Existing sitemap preserved."
            )

        products = list(reader)

    if len(products) < MIN_PRODUCT_URLS:
        raise ValueError(
            "Sitemap safety check failed: "
            f"only {len(products)} feed products. "
            "Existing sitemap preserved."
        )

    root = ET.Element(
        f"{{{SITEMAP_NS}}}urlset"
    )

    main_links = [
        SITE_URL,
        SITE_URL + "?department=saree",
        SITE_URL + "?department=dupatta",
    ]

    for link in main_links:
        add_url(root, link)

    seen_links = set(main_links)
    seen_codes = set()

    product_count = 0

    for line_number, product in enumerate(
        products,
        start=2,
    ):
        code = str(
            product.get("id") or ""
        ).strip()

        link = str(
            product.get("link") or ""
        ).strip()

        image_link = str(
            product.get("image_link") or ""
        ).strip()

        availability = str(
            product.get("availability") or ""
        ).strip().lower()

        if not code:
            raise ValueError(
                f"Missing product ID on row {line_number}"
            )

        if code in seen_codes:
            raise ValueError(
                f"Duplicate product ID: {code}"
            )

        seen_codes.add(code)

        if availability != "in_stock":
            raise ValueError(
                f"Inactive product in Merchant feed: {code}. "
                "Regenerate the feed first."
            )

        validate_product_link(
            link,
            line_number,
        )

        validate_image_link(
            image_link,
            line_number,
        )

        validate_price(
            product.get("price"),
            line_number,
        )

        if link in seen_links:
            raise ValueError(
                f"Duplicate product URL: {link}"
            )

        add_url(
            root,
            link,
            image_link,
        )

        seen_links.add(link)
        product_count += 1

    if product_count != len(products):
        raise ValueError(
            "Sitemap product count mismatch."
        )

    if len(seen_links) > 50000:
        raise ValueError(
            "More than 50,000 sitemap URLs. "
            "Split sitemap files first."
        )

    # Do not invent lastmod timestamps.
    ET.indent(
        root,
        space="  ",
    )

    tree = ET.ElementTree(root)

    temporary = OUTPUT_FILE.with_suffix(
        ".xml.tmp"
    )

    try:
        tree.write(
            temporary,
            encoding="utf-8",
            xml_declaration=True,
        )

        # Validate the generated XML before replacing
        # the existing production sitemap.
        ET.parse(temporary)

        if temporary.stat().st_size > (
            50 * 1024 * 1024
        ):
            raise ValueError(
                "Sitemap is larger than 50 MB."
            )

        temporary.replace(
            OUTPUT_FILE
        )

    finally:
        if temporary.exists():
            temporary.unlink()

    print(f"Feed products: {len(products)}")
    print(f"Product URLs: {product_count}")
    print(f"Main/category URLs: {len(main_links)}")
    print(f"Total sitemap URLs: {len(seen_links)}")
    print(f"Sitemap saved: {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
